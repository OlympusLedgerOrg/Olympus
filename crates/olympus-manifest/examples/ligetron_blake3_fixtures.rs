use olympus_manifest::content::version::ProfileEntry;
use olympus_manifest::content::{
    commit::{content_digest, content_key, empty_fp_set_root, empty_meta_root, ItemPreimage},
    domains::Domain,
    tree::{empty_root, ItemPath, ItemTree, Terminal},
    verify_m1_open, verify_n1, OpenedItem,
};
use serde_json::{json, Value};
use std::{fmt::Write, fs, io, path::Path};

const PARTITION_BITS: u8 = 4;
const PATH_DEPTH: usize = 50;

fn byte_arg(bytes: &[u8]) -> Value {
    json!({"hex": bytes.iter().map(|byte| format!("{byte:02x}")).collect::<String>()})
}

fn flipped(mut key: [u8; 32], bit: usize) -> [u8; 32] {
    key[bit / 8] ^= 0x80 >> (bit % 8);
    key
}

fn report_constant(output: &mut String, name: &str, bytes: &[u8; 32]) {
    write!(output, "constexpr uint8_t {name}[32] = {{").unwrap();
    for byte in bytes {
        write!(output, "0x{byte:02x},").unwrap();
    }
    writeln!(output, "}};").unwrap();
}

fn write_domains(output_dir: &Path) -> io::Result<()> {
    let mut output = String::from("// Generated by blake3_depth50.rs from Olympus domain keys.\n");
    for (name, domain) in [
        ("kLeaf", Domain::Leaf),
        ("kNode", Domain::Node),
        ("kPartition", Domain::Part),
        ("kTop", Domain::Top),
        ("kItem", Domain::Item),
    ] {
        report_constant(&mut output, name, domain.key());
    }
    report_constant(&mut output, "kEmptyRoot", &empty_root());
    fs::write(output_dir.join("domains.h"), output)
}

fn path_bytes(siblings: &[[u8; 32]]) -> Value {
    if siblings.is_empty() {
        byte_arg(&[0])
    } else {
        byte_arg(siblings.as_flattened())
    }
}

fn args(mode: u8, tree: &ItemTree, key: &[u8; 32], path: &ItemPath, witness: &[u8]) -> Value {
    assert_eq!(path.siblings.len() + usize::from(tree.p()), PATH_DEPTH);
    json!([
        {"i64": mode},
        byte_arg(&tree.root()),
        byte_arg(key),
        {"i64": tree.p()},
        {"i64": path.siblings.len()},
        byte_arg(&path.partition_count.to_be_bytes()),
        byte_arg(witness),
        path_bytes(&path.siblings),
        path_bytes(&path.top_siblings),
    ])
}

fn absence(tree: &ItemTree, key: &[u8; 32], expect_empty: bool) -> Value {
    let path = tree.path(key);
    verify_n1(tree.p(), &tree.root(), key, &path).unwrap();
    match path.terminal {
        Terminal::Empty => {
            assert!(expect_empty);
            args(2, tree, key, &path, &[0])
        }
        Terminal::Leaf {
            key: neighbor,
            commitment,
        } => {
            assert!(!expect_empty);
            let mut witness = [0; 64];
            witness[..32].copy_from_slice(&neighbor);
            witness[32..].copy_from_slice(&commitment);
            args(1, tree, key, &path, &witness)
        }
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output_dir = std::env::args_os()
        .nth(1)
        .ok_or("usage: ligetron_blake3_fixtures OUTPUT_DIR")?;
    let output_dir = Path::new(&output_dir);
    fs::create_dir_all(output_dir)?;
    let data = b"Olympus private dataset proof benchmark";
    let content_digest = content_digest(data);
    let key = content_key("bytes/raw", 1, &content_digest);
    let preimage = ItemPreimage {
        profile_index: 0,
        canonical_len: data.len() as u64,
        content_digest,
        fp_set_root: empty_fp_set_root(),
        occurrence_count: 1,
        meta_root: empty_meta_root(),
    };

    // Force uncommon long prefixes without building billions of leaves.
    let common_leaf = (key, preimage.commitment());
    let build = |split_bit| {
        ItemTree::build(
            PARTITION_BITS,
            vec![common_leaf, (flipped(key, split_bit), [42; 32])],
        )
    };
    let tree = build(PATH_DEPTH - 1)?;
    let opened = OpenedItem {
        key,
        path: tree.path(&key),
        preimage,
    };
    let profiles = [ProfileEntry {
        id: "bytes/raw".into(),
        version: 1,
        implementation_id: "olympus=0.1.0".into(),
    }];
    verify_m1_open(PARTITION_BITS, &tree.root(), &profiles, &opened)?;
    let empty_tree = build(PATH_DEPTH)?;
    let cases = json!({
        "membership-50": args(0, &tree, &key, &opened.path, &preimage.to_bytes()),
        "absence-neighbor-50": absence(&tree, &flipped(key, 255), false),
        "absence-empty-50": absence(&empty_tree, &flipped(key, PATH_DEPTH - 1), true),
    });
    write_domains(output_dir)?;
    fs::write(
        output_dir.join("fixtures.json"),
        serde_json::to_string_pretty(&cases)?,
    )?;
    Ok(())
}
